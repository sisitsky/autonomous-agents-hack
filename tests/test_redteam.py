# ---------------------------------------------------------------- engine: red-team outcomes

def _rt_insured(counts=None):
    T = ["wrong_information", "unauthorized_commitment", "data_leakage", "prompt_injection"]
    ins = {"id": "x", "provider": "provider_a", "perils": {t: {"outputs_per_year": 2_000_000} for t in T},
           "factors": {}, "policy": {"limit_per_claim": 1_000_000, "aggregate_limit": 2_000_000, "deductible": 10_000}}
    if counts is not None:
        ins["red_team"] = {"tested": 40, "suite": "adversarial", "suite_id": "customer_service",
                           "failures_by_type": dict(zip(T, counts))}
    return ins


def test_failures_raise_price_and_no_test_uses_portfolio(params):
    bad, good, none = (price(_rt_insured(c), params, **FAST)["gross_premium"]
                       for c in ((5, 7, 5, 7), (0, 0, 0, 0), None))
    assert good < none < bad


def test_bad_red_team_counts_rejected(params):
    ins = _rt_insured((20, 20, 1, 0))           # 41 failures in 40 cases
    with pytest.raises(ValueError):
        price(ins, params, **FAST)
    ins = _rt_insured((1, 1, 1, 1)); ins["red_team"]["failures_by_type"]["vibes"] = 1
    with pytest.raises(ValueError):
        price(ins, params, **FAST)


def test_tornado_shows_red_team_parameters(params):
    paths = [b["parameter"] for b in tornado(_rt_insured((5, 7, 5, 7)), params, n_years=20000)["bars"]]
    assert "perils.data_leakage.frequency.p_fail" in paths
    assert "perils.prompt_injection.frequency.adversarial_to_live" in paths
