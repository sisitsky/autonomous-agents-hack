# ---------------------------------------------------------------- red-team agent

def test_redteam_finds_planted_flaws(run_dir):
    s = redteam.run(str(run_dir), scorer="patterns")
    assert (s["tested"], s["failures"], s["errors"]) == (40, 24, 0)
    assert all(c["failures"] > 0 for c in s["by_category"].values())
    assert s["by_failure_type"]["data_leak"] == s["by_category"]["data_leakage"]["failures"]


def test_redteam_writes_counts_and_logs(run_dir):
    redteam.run(str(run_dir), scorer="patterns")
    text = (run_dir / "insured.yaml").read_text()
    assert text.startswith("# Generated by the intake agent")        # header kept
    rt = yaml.safe_load(text)["red_team"]
    assert rt["tested"] == 40 and rt["failures"] == 24 and rt["suite"] == "adversarial"
    lines = (run_dir / "redteam" / "cases.jsonl").read_text().splitlines()
    assert len(lines) == 40
    d01 = next(json.loads(l) for l in lines if json.loads(l)["id"] == "d01")
    assert d01["verdict"] == "material_failure" and "Alder Lane" in d01["reply"]


def test_dry_run_leaves_insured_alone(run_dir):
    before = (run_dir / "insured.yaml").read_text()
    redteam.run(str(run_dir), scorer="patterns", update_insured=False)
    assert (run_dir / "insured.yaml").read_text() == before


def test_judge_verdict_counts_and_disagreements_logged(run_dir, monkeypatch):
    # Stub judge: passes everything, so every pattern failure is a disagreement.
    monkeypatch.setattr(redteam, "llm_available", lambda: True)
    monkeypatch.setattr(redteam, "score_judge", lambda c, r, g: {
        "verdict": "pass", "failure_type": "none", "quote": "", "reason": "stub"})
    s = redteam.run(str(run_dir), scorer="judge")
    assert s["failures"] == 0 and s["scorer"] == "judge"
    assert len(s["disagreements"]) == 24


