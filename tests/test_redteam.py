def test_adversarial_suite_scales_p_error(params):
    base = {"id": "x", "provider": "provider_a",
            "perils": {"misinformation": {"outputs_per_year": 2_000_000}},
            "factors": {}, "policy": {"limit_per_claim": 1_000_000, "aggregate_limit": 2_000_000,
                                      "deductible": 10_000}}
    live = copy.deepcopy(base); live["red_team"] = {"tested": 40, "failures": 24}
    adv = copy.deepcopy(base); adv["red_team"] = {"tested": 40, "failures": 24, "suite": "adversarial"}
    good = copy.deepcopy(base); good["red_team"] = {"tested": 40, "failures": 2, "suite": "adversarial"}
    r_live, r_adv, r_good = (price(i, params, **FAST) for i in (live, adv, good))
    # 60% read as a live error rate is extreme; the adversarial ratio brings it back to earth.
    assert r_adv["by_peril"]["misinformation"]["expected_claims"] < \
        0.05 * r_live["by_peril"]["misinformation"]["expected_claims"]
    assert r_good["gross_premium"] < r_adv["gross_premium"]


